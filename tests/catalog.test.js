import test from 'node:test';
import assert from 'node:assert/strict';

import { renderCatalog, scanTranscriptUrls } from '../src/catalog.js';
import { renderFrontmatter } from '../src/frontmatter.js';

/**
 * A transcript exactly as the writer produces one: seven keys, settled order,
 * `title`/`channel`/`duration` double-quoted.
 */
function transcript(overrides = {}) {
  const video = {
    title: 'A Talk',
    url: 'https://www.youtube.com/watch?v=o3CX_Y59_74',
    channel: 'freeCodeCamp.org',
    duration: '41:18',
    upload_date: '2026-09-10',
    fetched: '2026-09-16T14:03:05Z',
    subtitles: 'auto',
    ...overrides,
  };

  return [
    '---',
    `title: "${video.title}"`,
    `url: ${video.url}`,
    `channel: "${video.channel}"`,
    `duration: "${video.duration}"`,
    `upload_date: ${video.upload_date}`,
    `fetched: ${video.fetched}`,
    `subtitles: ${video.subtitles}`,
    '---',
    '',
    'Some prose.',
    '',
  ].join('\n');
}

test('the catalog is a heading, a regeneration note and the five settled columns', () => {
  const { markdown, warnings } = renderCatalog([{ path: 'a-channel/a-talk.md', text: transcript() }]);

  assert.deepEqual(warnings, []);
  assert.equal(
    markdown,
    [
      '# Transcripts',
      '',
      '1 transcripts, regenerated by yt-transcript catalog',
      '',
      '| Title | Channel | Duration | Uploaded | Subtitles |',
      '| --- | --- | --- | --- | --- |',
      '| [A Talk](a-channel/a-talk.md) | freeCodeCamp.org | 41:18 | 2026-09-10 | auto |',
      '',
    ].join('\n'),
  );
});

test('rows sort by upload date descending, ties broken by title ascending', () => {
  const { markdown } = renderCatalog([
    { path: 'a-channel/beta.md', text: transcript({ title: 'Beta', upload_date: '2026-01-02' }) },
    { path: 'a-channel/older.md', text: transcript({ title: 'Older', upload_date: '2025-12-31' }) },
    { path: 'a-channel/alpha.md', text: transcript({ title: 'Alpha', upload_date: '2026-01-02' }) },
    { path: 'a-channel/newest.md', text: transcript({ title: 'Newest', upload_date: '2026-03-04' }) },
  ]);

  const titles = [...markdown.matchAll(/^\| \[([^\]]+)\]/gm)].map((match) => match[1]);
  assert.deepEqual(titles, ['Newest', 'Alpha', 'Beta', 'Older']);
});

test('a pipe in a title is escaped in the catalog cell only', () => {
  const text = transcript({ title: 'Rust | Go | C' });
  const { markdown } = renderCatalog([{ path: 'a-channel/rust-go-c.md', text }]);

  assert.match(markdown, /\| \[Rust \\\| Go \\\| C\]\(a-channel\/rust-go-c\.md\) \|/);
  // The row still has exactly the five settled columns: the escape held.
  const row = markdown.split('\n').at(-2);
  assert.equal(row.split(/(?<!\\)\|/).length - 2, 5);
  // The frontmatter contract is untouched — the escape lives in the cell.
  assert.match(text, /^title: "Rust \| Go \| C"$/m);
});

test('zero transcripts yields the heading and the count line, and no table', () => {
  const { markdown, warnings } = renderCatalog([]);

  assert.deepEqual(warnings, []);
  assert.equal(
    markdown,
    ['# Transcripts', '', '0 transcripts, regenerated by yt-transcript catalog', ''].join('\n'),
  );
});

test('the catalog never lists itself, by the scan rule rather than by filename', () => {
  const { markdown, warnings } = renderCatalog([
    { path: 'README.md', text: '# Transcripts\n\n1 transcripts, regenerated by yt-transcript catalog\n' },
    { path: 'notes.md', text: '# Notes\n\nA file somebody dropped in here.\n' },
    { path: 'a-channel/a-talk.md', text: transcript() },
  ]);

  // No frontmatter is not a malformed transcript — it is not a transcript.
  assert.deepEqual(warnings, []);
  assert.match(markdown, /^1 transcripts, /m);
  assert.doesNotMatch(markdown, /README/);
  assert.doesNotMatch(markdown, /notes\.md/);
});

test('a malformed transcript is named in a warning and skipped, the rest still written', () => {
  const truncated = '---\ntitle: "Cut Off"\nurl: https://www.youtube.com/watch?v=aaaaaaaaaaa\n';
  const incomplete = transcript({ title: 'Missing A Key' }).replace(/^channel: .*$/m, '');

  const { markdown, warnings } = renderCatalog([
    { path: 'cut-off.md', text: truncated },
    { path: 'missing-a-key.md', text: incomplete },
    { path: 'a-channel/a-talk.md', text: transcript() },
  ]);

  assert.equal(warnings.length, 2);
  for (const [file, warning] of [
    ['cut-off.md', warnings[0]],
    ['missing-a-key.md', warnings[1]],
  ]) {
    assert.ok(warning.includes(file), `the warning does not name ${file}: ${warning}`);
    assert.match(warning, /re-download/i);
  }

  // One bad file must not cost the whole catalog.
  assert.match(markdown, /^1 transcripts, /m);
  assert.match(markdown, /\[A Talk\]\(a-channel\/a-talk\.md\)/);
});

test('CRLF frontmatter and a leading byte-order mark still read as a transcript', () => {
  const { markdown, warnings } = renderCatalog([
    { path: 'a-channel/crlf.md', text: `﻿${transcript({ title: 'Windows' }).replace(/\n/g, '\r\n')}` },
  ]);

  assert.deepEqual(warnings, []);
  assert.match(markdown, /\[Windows\]\(a-channel\/crlf\.md\)/);
});

/**
 * The writer and this reader are two halves of one contract living in two
 * modules, so the escaping is pinned against `renderFrontmatter`'s real output
 * rather than against a hand-typed imitation of it.
 */
test('a title the writer had to escape survives the round trip into a cell', () => {
  const text = `${renderFrontmatter({
    title: '/wayfinder: Nothing | is "too" big \\ wide',
    url: 'https://www.youtube.com/watch?v=o3CX_Y59_74',
    channel: 'freeCodeCamp.org',
    duration: '41:18',
    uploadDate: '20260910',
    fetchedAt: new Date('2026-09-16T14:03:05.123Z'),
    subtitles: 'auto',
  })}\n\nProse.\n`;

  const { markdown, warnings } = renderCatalog([{ path: 'a-channel/wayfinder.md', text }]);

  assert.deepEqual(warnings, []);
  assert.match(
    markdown,
    /\| \[\/wayfinder: Nothing \\\| is "too" big \\ wide\]\(a-channel\/wayfinder\.md\) \| freeCodeCamp\.org \| 41:18 \| 2026-09-10 \| auto \|/,
  );
});

// The skip set a batch subtracts, read through the very same scan.

test('the scan reads back the url the writer really wrote', () => {
  // Pinned against `renderFrontmatter`'s output, not a hand-typed imitation:
  // a quoting change there must fail here rather than silently re-fetch every
  // video in every batch.
  const text = `${renderFrontmatter({
    title: 'A Talk',
    url: 'https://www.youtube.com/watch?v=o3CX_Y59_74',
    channel: 'freeCodeCamp.org',
    duration: '41:18',
    uploadDate: '20260910',
    fetchedAt: new Date('2026-09-16T14:03:05.123Z'),
    subtitles: 'auto',
  })}\n\nProse.\n`;

  assert.deepEqual(scanTranscriptUrls([{ path: 'renamed-by-hand.md', text }]), [
    'https://www.youtube.com/watch?v=o3CX_Y59_74',
  ]);
});

test('the scan ignores the catalog and any file too broken to identify', () => {
  const urls = scanTranscriptUrls([
    { path: 'README.md', text: renderCatalog([]).markdown },
    { path: 'broken.md', text: '---\ntitle: "Half"\n' },
    { path: 'a-channel/a-talk.md', text: transcript() },
  ]);

  assert.deepEqual(urls, ['https://www.youtube.com/watch?v=o3CX_Y59_74']);
});

// Where a transcript sits (ADR-0008): its row links to its path under `transcripts/`.

test('a transcript at the top level is still listed, with one warning naming it', () => {
  const { markdown, warnings } = renderCatalog([
    { path: 'loose.md', text: transcript({ title: 'Loose' }) },
    { path: 'a-channel/filed.md', text: transcript({ title: 'Filed' }) },
  ]);

  assert.match(markdown, /^2 transcripts, /m);
  assert.match(markdown, /\[Loose\]\(loose\.md\)/);
  assert.equal(warnings.length, 1);
  assert.ok(warnings[0].includes('loose.md'), warnings[0]);
  assert.match(warnings[0], /outside a channel folder/);
  assert.match(warnings[0], /move it/i);
});
